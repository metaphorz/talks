"""Build data.js for the Models of Amelia Island deck.

Reads the real geometry and data from the model folders in ~/code/ameliaisland and writes one
compact script (window.AMELIA) the slides can draw without a server:

  island   simplified geomorphology snapshots (Pleistocene core, sandbars,
           Holocene wedge by age, Egans Creek marsh, beach ridges, jetties)
  sea      the Hawkes 2016 / Lambeck sea-level curve used by both
           geomorphology and drumstick
  trees    every Fernandina Beach city-inventory point, tagged by species

Coordinates are metres east/south of a fixed origin (NW corner), rounded.
Run:  python3 src/build_data.py      (from ~/code/talks/models; reads ~/code/ameliaisland)
"""
import json, math, os, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'ameliaisland'))  # the model folders
OUT = os.path.normpath(os.path.join(HERE, '..', 'data.js'))

LON0, LAT0 = -81.52, 30.72          # origin (NW of the island)
KX = 111320 * math.cos(math.radians(30.62))
KY = 110540


def xy(p):
    return [round((p[0] - LON0) * KX), round((LAT0 - p[1]) * KY)]


def rdp(pts, eps):
    """Ramer-Douglas-Peucker line simplification."""
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-9
    best, idx = 0, 0
    for i in range(1, len(pts) - 1):
        x0, y0 = pts[i]
        d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / n
        if d > best:
            best, idx = d, i
    if best > eps:
        return rdp(pts[:idx + 1], eps)[:-1] + rdp(pts[idx:], eps)
    return [pts[0], pts[-1]]


def rings(geom, eps, min_pts=4):
    t, c = geom['type'], geom['coordinates']
    polys = [c] if t == 'Polygon' else c if t == 'MultiPolygon' else None
    if polys is None:                       # LineString
        return [rdp([xy(p) for p in c], eps)]
    out = []
    for poly in polys:
        ring = [xy(p) for p in poly[0]]          # outer ring only
        # a closed ring starts and ends on the same point, so split it at the
        # vertex farthest from the start and simplify the two halves
        far = max(range(len(ring)), key=lambda i: math.dist(ring[0], ring[i]))
        r = rdp(ring[:far + 1], eps)[:-1] + rdp(ring[far:], eps)
        if len(r) >= min_pts:
            out.append(r)
    return out


def island():
    gj = json.load(open(os.path.join(ROOT, 'geomorphology', 'data', 'snapshots.geojson')))
    feats = {}
    for f in gj['features']:
        p = f['properties']
        eps = 25 if p['kind'] in ('jetty', 'beach-ridge') else 45
        if p['kind'] == 'hint':
            continue
        feats[p['id']] = {
            'kind': p['kind'], 'name': p['name'],
            'from': p['visible_from_ka'], 'to': p['visible_to_ka'],
            'rings': rings(f['geometry'], eps),
        }
    return feats


def sea():
    d = json.load(open(os.path.join(ROOT, 'geomorphology', 'data', 'sea_level.json')))
    return d['points']


def trees():
    gj = json.load(open(os.path.join(ROOT, 'Amelia Island Trees', 'data', 'fernandina-trees.geojson')))
    names = [(f['properties'].get('common') or 'Not recorded').strip() for f in gj['features']]
    top = [n for n, _ in collections.Counter(names).most_common(8)]
    counts = collections.Counter(names)
    pts = []
    for f, n in zip(gj['features'], names):
        g = f.get('geometry')
        if not g:
            continue
        x, y = xy(g['coordinates'])
        k = top.index(n) if n in top else len(top)
        dead = 1 if (f['properties'].get('condition2') or '') == 'Dead' else 0
        pts += [x, y, k * 2 + dead]
    cond = collections.Counter((f['properties'].get('condition2') or 'Not recorded') for f in gj['features'])
    return {
        'species': top + ['Other species'],
        'counts': [counts[n] for n in top] + [len(names) - sum(counts[n] for n in top)],
        'total': len(names),
        'conditions': cond.most_common(),
        'pts': pts,
    }


def main():
    data = {'origin': [LON0, LAT0], 'island': island(), 'sea': sea(), 'trees': trees()}
    js = ('// Generated by src/build_data.py from ~/code/ameliaisland. Do not edit.\n'
          'window.AMELIA=' + json.dumps(data, separators=(',', ':')) + ';\n')
    open(OUT, 'w').write(js)
    print('wrote', OUT, round(len(js) / 1024), 'KB',
          '| island features', len(data['island']), '| trees', data['trees']['total'])


if __name__ == '__main__':
    main()
